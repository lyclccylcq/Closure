#!/usr/bin/env python3
"""Record or verify SHA-256 hashes without creating another copy of the models."""
import argparse
import hashlib
import json
from pathlib import Path


def digest(path):
    before = path.stat()
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(chunk)
    after = path.stat()
    if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
        raise RuntimeError(f"File changed while hashing: {path}")
    return value.hexdigest(), after.st_size


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=Path)
    parser.add_argument("--root", action="append", default=[], metavar="NAME=PATH")
    parser.add_argument("--verify", type=Path, metavar="SERVER_BASE")
    parser.add_argument("--allow-regenerated-bytecode", action="store_true",
                        help="Allow changed __pycache__/*.pyc after running Python on Linux; still verify all source/model data")
    args = parser.parse_args()
    if args.verify:
        data = json.loads(args.manifest.read_text())
        if data.get("format") != 1:
            raise ValueError("Unsupported manifest format")
        errors = []
        regenerated = []
        for entry in data["files"]:
            relative = Path(entry["path"])
            if relative.is_absolute() or ".." in relative.parts:
                raise ValueError(f"Unsafe manifest path: {relative}")
            path = args.verify / relative
            try:
                actual, size = digest(path)
                if actual != entry["sha256"] or size != entry["bytes"]:
                    if args.allow_regenerated_bytecode and "__pycache__" in relative.parts and relative.suffix == ".pyc":
                        regenerated.append(str(relative))
                    else:
                        errors.append(f"Changed: {relative}")
            except OSError:
                errors.append(f"Missing/unreadable: {relative}")
        if errors:
            for error in errors:
                print(error)
            raise SystemExit(1)
        print(f"Verified {len(data['files']) - len(regenerated)} unchanged files; "
              f"{len(regenerated)} Python bytecode files regenerated by the Linux runtime.")
        return
    if not args.root:
        parser.error("Supply at least one --root NAME=PATH")
    roots = {}
    entries = []
    for spec in args.root:
        name, location = spec.split("=", 1)
        if not name or name in roots or name in (".", "..") or "/" in name or "\\" in name:
            raise ValueError(f"Invalid or duplicate root name: {name}")
        root = Path(location).expanduser().resolve(strict=True)
        if not root.is_dir():
            raise ValueError(f"Root is not a directory: {root}")
        roots[name] = str(root)
        for path in sorted(root.rglob("*")):
            if path.is_symlink():
                raise ValueError(f"Resolve symlink before transferring: {path}")
            if path.is_file():
                sha, size = digest(path)
                entries.append({"path": str(Path(name) / path.relative_to(root)),
                                "bytes": size, "sha256": sha})
    data = {"format": 1, "source_roots": roots, "files": entries,
            "bytes": sum(entry["bytes"] for entry in entries)}
    args.manifest.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    print(f"Recorded {len(entries)} files ({data['bytes']} bytes) in {args.manifest}.")


if __name__ == "__main__":
    main()
